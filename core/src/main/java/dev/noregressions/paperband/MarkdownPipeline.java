package dev.noregressions.paperband;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.ZonedDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The full processing pipeline for a set of markdown files:
 *
 * <ol>
 *   <li>pre pass: each file through Pebble with {@code {{ }}} / {@code {% %}};</li>
 *   <li>parse all of them into a draft {@link CombinedAst};</li>
 *   <li>post pass: each pre-pass output through Pebble with {@code [[ ]]} / {@code [% %]};</li>
 *   <li>parse the post-pass output into the final {@link CombinedAst}.</li>
 * </ol>
 *
 * Both passes see these variables, besides each file's {@code page} and {@code file}:
 * <ul>
 *   <li>{@code site}: a {@link Site}. In the pre pass it has every file's path and front matter;
 *       in the post pass it also has the draft content, including content generated by another
 *       file's pre pass (but not another file's post-pass output);</li>
 *   <li>{@code data}: YAML/JSON data files (see {@link DataLoader});</li>
 *   <li>{@code env}: the environment variables named in the config, and no others;</li>
 *   <li>{@code build}: {@code build.date} (when the run started) and {@code build.files} (how many files);</li>
 *   <li>the config's {@code vars}, as top-level variables.</li>
 * </ul>
 */
public final class MarkdownPipeline {

    /** Variable names the pipeline sets itself, so {@code vars} can't use them. */
    public static final Set<String> RESERVED = Set.of("page", "file", "site", "data", "env", "build");

    public record Source(Path path, String markdown) {
    }

    /**
     * @param draft the AST after the pre pass, as the post pass saw it
     * @param ast   the final AST
     * @param texts each file's text at every stage, by path
     */
    public record Result(CombinedAst draft, CombinedAst ast, Map<Path, Texts> texts) {
    }

    /** The processing stages a file's text can be shown at. */
    public enum Stage {
        /** As the author wrote it. */
        ORIGINAL,
        /** After the pre pass ({@code {{ }}}, {@code {% %}}). */
        PRE,
        /** After the post pass ({@code [[ ]]}, {@code [% %]}): what the markdown parser read. */
        FINAL
    }

    /** One file's text at each stage. */
    public record Texts(String original, String pre, String post) {

        public String at(Stage stage) {
            return switch (stage) {
                case ORIGINAL -> original;
                case PRE -> pre;
                case FINAL -> post;
            };
        }
    }

    /**
     * @param templates directory for {@code extends} and {@code include}
     * @param vars      top-level template variables
     * @param data      exposed as {@code data}, usually from {@link DataLoader}
     * @param env       exposed as {@code env}
     * @param clock     source of {@code build.date}
     */
    public record Config(Path templates, Map<String, String> vars, Map<String, Object> data,
                         Map<String, String> env, Clock clock, AutoIndex autoIndex) {

        public Config(Path templates, Map<String, String> vars, Map<String, Object> data, Map<String, String> env,
                      Clock clock) {
            this(templates, vars, data, env, clock, null);
        }

        public Config {
            List<String> clashes = vars.keySet().stream().filter(RESERVED::contains).sorted().toList();
            if (!clashes.isEmpty()) {
                throw new IllegalArgumentException("reserved variable name(s) " + clashes
                        + "; these are set by the pipeline: " + RESERVED.stream().sorted().toList());
            }
        }

        public static Config defaults() {
            return new Config(Path.of(PebblePreprocessor.DEFAULT_TEMPLATES), Map.of(), Map.of(), Map.of(),
                    Clock.systemDefaultZone());
        }

        public Config withTemplates(Path templates) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }

        public Config withVars(Map<String, String> vars) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }

        public Config withData(Map<String, Object> data) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }

        public Config withEnv(Map<String, String> env) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }

        /** Index terms to find by rule as each file is parsed ({@link AutoIndex}); null for none. */
        public Config withAutoIndex(AutoIndex autoIndex) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }

        public Config withClock(Clock clock) {
            return new Config(templates, vars, data, env, clock, autoIndex);
        }
    }

    private final Config config;
    private final PebblePreprocessor pre;
    private final PebblePreprocessor post;

    public MarkdownPipeline(Path templatesDir, Map<String, String> vars) {
        this(Config.defaults().withTemplates(templatesDir).withVars(vars));
    }

    public MarkdownPipeline(Config config) {
        this.config = config;
        this.pre = new PebblePreprocessor(PebblePreprocessor.Pass.PRE, config.templates(), config.vars());
        this.post = new PebblePreprocessor(PebblePreprocessor.Pass.POST, config.templates(), config.vars());
    }

    public Result runFiles(List<Path> paths) throws IOException {
        List<Source> sources = new ArrayList<>();
        for (Path p : paths) {
            sources.add(new Source(p, Files.readString(p, StandardCharsets.UTF_8)));
        }
        return run(sources, null);
    }

    public Result run(List<Source> sources) throws IOException {
        return run(sources, null);
    }

    /**
     * @param sequence the files that will be written out, in order, exposed to templates as
     *                 {@code site.sequence}; null means all sources
     */
    public Result run(List<Source> sources, List<Path> sequence) throws IOException {
        Map<String, Object> shared = new HashMap<>();
        shared.put("data", config.data());
        shared.put("env", config.env());
        shared.put("build", Map.of("date", ZonedDateTime.now(config.clock()), "files", sources.size()));

        // Front matter isn't templated, so every file's is known before the pre pass.
        Map<Path, Map<String, Object>> frontMatter = new LinkedHashMap<>();
        for (Source s : sources) {
            frontMatter.put(s.path(), FrontMatter.split(s.path(), s.markdown()).data());
        }
        Map<String, Object> preContext = new HashMap<>(shared);
        preContext.put("site", Site.ofFrontMatter(frontMatter, sequence));

        List<Source> preprocessed = new ArrayList<>();
        CombinedAst draft = new CombinedAst(Preprocessor.NONE, config.autoIndex());
        for (Source s : sources) {
            Source out = new Source(s.path(), pre.process(s.path(), s.markdown(), preContext));
            preprocessed.add(out);
            draft.add(out.path(), out.markdown());
        }

        Map<String, Object> postContext = new HashMap<>(shared);
        postContext.put("site", new Site(draft, sequence));
        Map<Path, String> postprocessed = new HashMap<>();
        CombinedAst ast = new CombinedAst((path, markdown) -> {
            String out = post.process(path, markdown, postContext);
            postprocessed.put(path, out);
            return out;
        }, config.autoIndex());
        for (Source s : preprocessed) {
            ast.add(s.path(), s.markdown());
        }

        Map<Path, Texts> texts = new LinkedHashMap<>();
        for (int i = 0; i < sources.size(); i++) {
            Path p = sources.get(i).path();
            texts.put(p, new Texts(sources.get(i).markdown(), preprocessed.get(i).markdown(), postprocessed.get(p)));
        }
        return new Result(draft, ast, java.util.Collections.unmodifiableMap(texts));
    }
}
